import fs from 'fs'
import path from 'path'
import ignore from 'ignore'
import { program } from 'commander'
import { compressContent } from './utils.js'

// Read package.json for version and metadata
let pkgStr = '{}'
try {
    const pkgPath = new URL('../package.json', import.meta.url)
    pkgStr = fs.readFileSync(pkgPath, 'utf8')
} catch (e) {
    try {
        // Fallback for when running via vite-node locally
        pkgStr = fs.readFileSync('./package.json', 'utf8')
    } catch(e2) {
        // ignore
    }
}
const pkg = JSON.parse(pkgStr)
const VERSION = pkg.version || 'unknown'
const TOOL_NAME = pkg.name || '@json-express/context-builder'

program
    .name('context-builder')
    .description('A cli tool to build your project context that can be uploaded to ai when chatting')
    .version(VERSION, '-v, --version', 'output the current version')
    .argument('[paths...]', 'Paths (directories or files) to include in the context. Defaults to current directory if none specified.')
    .option('-o, --out <directory>', 'Output directory', '.')
    .option('-n, --name <filename>', 'Output filename (default dynamic based on format)')
    .option('-f, --format <format>', 'Output format (md, txt, json)', 'md')
    .option('-c, --compress', 'Compress output to save LLM tokens by removing whitespace and comments', false)
    .option('--copy', 'Skip creating a file and only copy the context to clipboard', false)
    .action(async (paths, options) => {
        const startPaths = paths.length > 0 ? paths : ['.']

        let outDir = options.out
        // Handle common UX mistake where user might input `./dist` instead of `dist`
        if (outDir.startsWith('./') && outDir.length > 2) {
            outDir = outDir.slice(2)
        }

        const format = options.format.toLowerCase()
        if (!['md', 'txt', 'json'].includes(format)) {
            console.error('Invalid format specified. Must be md, txt, or json.')
            process.exit(1)
        }

        const outName = options.name || `llm-context.${format}`
        const outputFilePath = path.join(outDir, outName)
        const isCompress = options.compress
        const isCopyOnly = options.copy

        // Ensure output directory exists
        if (!fs.existsSync(outDir)) {
            fs.mkdirSync(outDir, { recursive: true })
        }

        // --- Ignore Logic Setup ---

        // 1. gitIg: For full exclusion from tree and content
        const gitIg = ignore()

        const gitignorePath = '.gitignore'
        if (fs.existsSync(gitignorePath)) {
            const gitignoreContent = fs.readFileSync(gitignorePath, 'utf8')
            gitIg.add(gitignoreContent)
        }
        gitIg.add('node_modules')
        // Automatically ignore the output file so it doesn't try to read itself
        gitIg.add(outName)
        gitIg.add('.git')

        // 2. contextIg: For content-only exclusion
        const contextIg = ignore()
        const contextIgnorePath = '.contextignore'
        if (fs.existsSync(contextIgnorePath)) {
            const contextIgnoreContent = fs.readFileSync(contextIgnorePath, 'utf8')
            contextIg.add(contextIgnoreContent)
        }

        // --- Main Script Logic ---

        let finalOutputString = ''

        // Write the main AI Prompt
        const aiPrompt = `# Codebase Context Snapshot
Generated by \`${TOOL_NAME}\` (v${VERSION})

## System Instructions
You are an expert AI developer assistant. Your task is to analyze the provided codebase and assist the user with feature implementation, debugging, or architectural advice.

### Data Structure:
1. **File Tree**: A complete map of the project hierarchy.
2. **File Contents**: The source code of the files included in this snapshot.

### Exclusion Rules:
- This snapshot honors \`.gitignore\` and \`.contextignore\`.
- Large assets, dependencies (e.g., \`node_modules\`), and binary files are omitted to maximize your context window efficiency.
- **Important**: If a file appears in the **File Tree** but its content is missing from the **File Contents** section, it has been intentionally excluded. If you need its contents to provide an accurate answer, please ask the user.

---
`

        // Data structure for JSON format
        const jsonOutput = {
            tool: TOOL_NAME,
            version: VERSION,
            trees: [],
            files:[]
        }

        if (format === 'md' || format === 'txt') {
            finalOutputString += aiPrompt + '\n'
        }

        const generateTree = (dir, prefix = '', isExplicit = false) => {
            if (!fs.existsSync(dir)) return ''

            // If it's a file, we don't generate a tree for it (it's handled by readPathAndWriteToFile)
            if (fs.statSync(dir).isFile()) return ''

            const allFiles = fs.readdirSync(dir)
            const allowedFiles = allFiles.filter(file => {
                const absolutePath = path.resolve(dir, file)
                const relativePath = path.relative(process.cwd(), absolutePath)

                // If the parent (dir) was explicitly requested, we still want to filter
                // its children by .gitignore unless the user wants everything.
                // Usually, the expected behavior is: explicit path is allowed,
                // but its contents follow standard rules.
                return !gitIg.ignores(relativePath)
            })

            let tree = ''
            allowedFiles.forEach((file, index) => {
                const filePath = path.join(dir, file)
                const absolutePath = path.resolve(filePath)
                const relativePath = path.relative(process.cwd(), absolutePath)

                // Standard ignore check for children
                if (gitIg.ignores(relativePath)) return;

                const isLast = index === allowedFiles.length - 1
                const connector = isLast ? '└── ' : '├── '

                tree += `${prefix}${connector}${file}\n`

                if (fs.statSync(filePath).isDirectory()) {
                    const newPrefix = prefix + (isLast ? '    ' : '│   ')
                    // Children are not explicit roots
                    tree += generateTree(filePath, newPrefix, false)
                }
            })
            return tree
        }

        // compressContent is imported from src/utils.js

        const readPathAndWriteToFile = (itemPath, isExplicit = false) => {
            if (!fs.existsSync(itemPath)) return

            const absolutePath = path.resolve(itemPath)
            const relativePath = path.relative(process.cwd(), absolutePath)
            const relativeCheckPath = relativePath.startsWith('..') ? path.basename(itemPath) : relativePath

            // If NOT explicit and it's in .gitignore, skip
            if (!isExplicit && relativeCheckPath && gitIg.ignores(relativeCheckPath)) {
                return
            }

            const stat = fs.statSync(itemPath)

            if (stat.isDirectory()) {
                const files = fs.readdirSync(itemPath)
                files.forEach(file => {
                    // Recursive calls for children are NOT explicit
                    readPathAndWriteToFile(path.join(itemPath, file), false)
                })
            } else if (stat.isFile()) {
                // If NOT explicit and it's in .contextignore, skip
                if (!isExplicit && contextIg.ignores(relativeCheckPath)) {
                    return
                } else {
                    const rawContent = fs.readFileSync(itemPath, 'utf8')
                    const displayPath = relativePath.startsWith('..') ? itemPath : relativePath
                    const ext = path.extname(itemPath).slice(1) || 'text'
                    const content = compressContent(rawContent, ext, isCompress)

                    if (format === 'json') {
                        jsonOutput.files.push({ path: displayPath, content: content })
                    } else if (format === 'md') {
                        finalOutputString += `### ${displayPath}\n\`\`\`${ext}\n${content}\n\`\`\`\n\n`
                    } else {
                        finalOutputString += `${displayPath}\n----------------------------------------\n${content}\n\n========================================\n\n`
                    }
                }
            }
        }

        // --- Execution ---

        console.log('Generating file tree(s)...')

        // Step 1: Generate all file trees and output them first
        startPaths.forEach(p => {
            const treeStructure = generateTree(p, '', true)
            const rootName = p === '.' ? path.basename(process.cwd()) : path.basename(p)

            if (format === 'json') {
                jsonOutput.trees.push({
                    directory: rootName,
                    tree: treeStructure
                })
            } else if (format === 'md') {
                finalOutputString += `## Project Tree: ${rootName}\n\`\`\`text\n${rootName}\n${treeStructure}\n\`\`\`\n\n`
            } else {
                finalOutputString += `Project Tree: ${rootName}\n${treeStructure}\n\n`
            }
        })

        console.log('Generating file contents...')

        // Step 2: Append all file contents below the generated trees
        startPaths.forEach(p => {
            console.log(`Processing path: ${p}`)
            readPathAndWriteToFile(p, true)
        })

        // Step 3: Serialize JSON if needed
        if (format === 'json') {
            finalOutputString = JSON.stringify(jsonOutput, null, 2)
        }

        const finalizeOutput = async () => {
            try {
                const clipboardy = (await import('clipboardy')).default;
                clipboardy.writeSync(finalOutputString);

                if (isCopyOnly) {
                    console.log(`Processing complete. The context has been copied to your clipboard (skipping file creation).`)
                } else {
                    fs.writeFileSync(outputFilePath, finalOutputString);
                    console.log(`Processing complete. The output has been written to ${outputFilePath} AND copied to your clipboard.`)
                }
            } catch (err) {
                console.error('Failed to copy to clipboard or write file:', err.message)
                if (!isCopyOnly) {
                    fs.writeFileSync(outputFilePath, finalOutputString);
                    console.log(`Processing complete. The output has been written to ${outputFilePath} (Clipboard copy failed).`)
                }
            }
        }

        await finalizeOutput()
    })

program.parse(process.argv)
